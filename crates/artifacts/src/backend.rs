/// Backend-neutral physical storage class selected by an owning domain.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ObjectStorageClass {
    /// Default hot object storage.
    #[default]
    Standard,
    /// Provider infrequent-access storage when supported.
    InfrequentAccess,
}

/// Metadata persisted atomically with one committed object.
#[derive(Clone, Debug, Default, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ObjectMetadata {
    /// Plaintext byte length.
    pub size: u64,
    /// Stable opaque `ETag` without HTTP quotes.
    pub etag: String,
    /// Commit time in Unix milliseconds.
    pub last_modified_ms: i64,
    /// Canonical user metadata.
    pub user: BTreeMap<String, String>,
    /// Standard HTTP content metadata.
    pub http: ObjectHttpMetadata,
    /// Physical storage class requested by the owning domain.
    pub storage_class: ObjectStorageClass,
    /// Lowercase hex MD5 advertised for an SSE-C object.
    pub ssec_key_md5: Option<String>,
}

