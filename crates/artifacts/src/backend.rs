/// Maximum canonical physical-key length admitted by the platform.
pub(crate) const OBJECT_KEY_MAX_BYTES: usize = 1024;

/// A validated backend physical key generated by a domain store.
#[derive(Clone, Debug, Eq, Hash, Ord, PartialEq, PartialOrd, Serialize)]
#[serde(transparent)]
pub struct ObjectKey(String);

impl<'de> Deserialize<'de> for ObjectKey {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        let value = String::deserialize(deserializer)?;
        Self::new(value).map_err(serde::de::Error::custom)
    }
}

impl ObjectKey {
    /// Validate a canonical host-generated ASCII physical key.
    pub fn new(value: impl Into<String>) -> Result<Self, BackendError> {
        let value = value.into();
        if value.is_empty()
            || value.len() > OBJECT_KEY_MAX_BYTES
            || value.starts_with('/')
            || value.ends_with('/')
            || value.split('/').any(|segment| {
                segment.is_empty()
                    || segment == "."
                    || segment == ".."
                    || segment.len() > 255
                    || !segment.bytes().all(|byte| {
                        byte.is_ascii_alphanumeric()
                            || matches!(byte, b'-' | b'_' | b'.' | b'=' | b'+' | b'@')
                    })
            })
        {
            return Err(BackendError::InvalidKey);
        }
        Ok(Self(value))
    }

    /// Borrow the canonical key string.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// Replayable bounded source for one object mutation.
pub enum ObjectSource {
    /// In-memory bytes.
    Bytes(Bytes),
    /// An already-opened regular file and its exact expected length.
    File {
        /// Already-opened regular file.
        file: File,
        /// Exact expected byte length.
        length: u64,
    },
}

impl std::fmt::Debug for ObjectSource {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Bytes(bytes) => formatter
                .debug_struct("ObjectSource::Bytes")
                .field("length", &bytes.len())
                .finish(),
            Self::File { length, .. } => formatter
                .debug_struct("ObjectSource::File")
                .field("length", length)
                .finish_non_exhaustive(),
        }
    }
}

impl ObjectSource {
    /// Exact source length.
    #[must_use]
    pub fn length(&self) -> u64 {
        match self {
            Self::Bytes(bytes) => bytes.len() as u64,
            Self::File { length, .. } => *length,
        }
    }

    fn validate(&self) -> Result<(), BackendError> {
        let Self::File { file, length } = self else {
            return Ok(());
        };
        let metadata = file.metadata().map_err(|_| BackendError::Unavailable)?;
        if !private_source_metadata(&metadata, *length) {
            return Err(BackendError::Corrupt);
        }
        Ok(())
    }
}

pub(crate) fn open_private_source(path: &Path, expected_length: u64) -> Result<File, BackendError> {
    let file = std::fs::OpenOptions::new()
        .read(true)
        .custom_flags(rustix::fs::OFlags::NOFOLLOW.bits() as i32)
        .open(path)
        .map_err(|_| BackendError::Unavailable)?;
    let metadata = file.metadata().map_err(|_| BackendError::Unavailable)?;
    if !private_source_metadata(&metadata, expected_length) {
        return Err(BackendError::Corrupt);
    }
    Ok(file)
}

fn private_source_metadata(metadata: &std::fs::Metadata, expected_length: u64) -> bool {
    metadata.file_type().is_file()
        && metadata.len() == expected_length
        && metadata.nlink() == 1
        && metadata.uid() == rustix::process::getuid().as_raw()
        && metadata.mode() & 0o077 == 0
}

