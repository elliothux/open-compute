/** Select the one host-network capability for tenant code, or disable it for validation. */
export function tenantGlobalOutbound(
  env: LoaderEnv,
  validation: boolean,
): Fetcher | null {
  if (validation) return null;
  if (env.OUTBOUND_NETWORK == null)
    throw bindingError("VERSION_INVARIANT_VIOLATION");
  return env.OUTBOUND_NETWORK;
}

/** Select compatibility metadata and resource limits only from the immutable snapshot. */
function workerCodeOptions(snapshot: RuntimeSnapshot): {
  compatibilityDate: string;
  compatibilityFlags: string[];
  allowExperimental: true;
  limits: { cpuMs: number; subRequests: number };
} {
  if (
    typeof snapshot.compatibilityDate !== "string" ||
    snapshot.compatibilityDate.length > 32 ||
    !Array.isArray(snapshot.compatibilityFlags) ||
    snapshot.compatibilityFlags.length > 64 ||
    !snapshot.compatibilityFlags.every(
      (flag) => typeof flag === "string" && flag.length <= 128,
    ) ||
    !Number.isSafeInteger(snapshot.limits?.cpuMs) ||
    !Number.isSafeInteger(snapshot.limits?.subRequests)
  ) {
    throw bindingError("VERSION_INVARIANT_VIOLATION");
  }
  return {
    compatibilityDate: snapshot.compatibilityDate,
    compatibilityFlags: [...snapshot.compatibilityFlags],
    allowExperimental: true,
    limits: {
      cpuMs: snapshot.limits.cpuMs,
      subRequests: snapshot.limits.subRequests,
    },
  };
}

/** Deployment startup must restore an admitted artifact instead of loading raw Python. */
export async function snapshotWorkerCode(
  env: LoaderEnv,
  snapshot: RuntimeSnapshot,
  scope: RuntimeSourceScope,
  token: string | null,
) {
  if (token === null) throw bindingError("BINDING_PROTOCOL_ERROR");
  const options = workerCodeOptions(snapshot);
  if (snapshot.mainModule?.endsWith(".py")) {
    if (snapshot.pythonPreparedSha256 === undefined)
      throw bindingError("PYTHON_PREPARED_ARTIFACT_MISSING");
    if (!/^[a-f0-9]{64}$/.test(snapshot.pythonPreparedSha256))
      throw bindingError("VERSION_INVARIANT_VIOLATION");
    return {
      ...options,
      openComputePythonSnapshot: await resolvePythonSnapshot(
        env,
        snapshot,
        scope,
        token,
      ),
    };
  }
  return options;
}

/** Require an unprepared Python deployment for the host's single-use preparation operation. */
export function pythonPreparationCode(snapshot: RuntimeSnapshot) {
  if (
    snapshot.contentKind !== "worker" ||
    snapshot.pythonPreparedSha256 !== undefined ||
    !snapshot.mainModule?.endsWith(".py")
  )
    throw bindingError("VERSION_INVARIANT_VIOLATION");
  return workerCodeOptions(snapshot);
}

function policyInteger(
  env: DoPolicyEnv,
  name: keyof DoPolicyEnv,
  maximum: number,
): number {
  const value = Number(env[name]);
  if (!Number.isSafeInteger(value) || value < 1 || value > maximum) {
    throw bindingError("DO_INTERNAL_PROTOCOL_ERROR");
  }
  return value;
}

/** Parse the platform-owned Durable Object policy environment. */
export function doPolicy(env: DoPolicyEnv): Readonly<DoPolicy> {
  return Object.freeze({
    maxObjectNameBytes: policyInteger(env, "DO_MAX_OBJECT_NAME_BYTES", 1024),
    maxFetchBodyBytes: policyInteger(
      env,
      "DO_MAX_FETCH_BODY_BYTES",
      64 * 1024 * 1024,
    ),
    dispatchTimeoutMs: policyInteger(
      env,
      "DO_DISPATCH_TIMEOUT_MS",
      5 * 60 * 1000,
    ),
    maxInFlightDispatches: policyInteger(
      env,
      "DO_MAX_IN_FLIGHT_DISPATCHES",
      4096,
    ),
  });
}

/** Return the immutable startup generation, optionally seeding it from trusted config. */
export function currentStartupGeneration(seed?: string | null): string {
  if (!startupGeneration) startupGeneration = seed || crypto.randomUUID();
  if (seed && startupGeneration !== seed)
    throw bindingError("BINDING_PROTOCOL_ERROR");
  return startupGeneration;
}

/** Resolve and strictly validate an immutable version snapshot. */
export async function resolveSnapshot(
  env: LoaderEnv,
  envelope: RuntimeEnvelope,
  scope: RuntimeSourceScope,
  internalToken: string | null,
): Promise<RuntimeSnapshot> {
  if (internalToken === null) throw bindingError("BINDING_PROTOCOL_ERROR");
  // Ingress already read route generation from SQLite. Runtime-visible
  // mutations bump that generation, so a hit is the same bytes the source
  // would re-hash. Validation and probe stay uncached.
  const cacheKey = warmSnapshotKey(envelope, scope);
  if (cacheKey) {
    const cached = warmRuntimeSnapshots.get(cacheKey);
    if (cached) {
      const size = warmRuntimeSnapshotSizes.get(cacheKey) ?? 0;
      warmRuntimeSnapshots.delete(cacheKey);
      warmRuntimeSnapshotSizes.delete(cacheKey);
      warmRuntimeSnapshots.set(cacheKey, cached);
      warmRuntimeSnapshotSizes.set(cacheKey, size);
      return cached;
    }
  }
  const response = await env.RUNTIME_SOURCE.fetch(
    `http://runtime-source${SOURCE_PATH}`,
    {
      method: "POST",
      headers: {
        "content-type": "application/json",
        [TOKEN_HEADER]: internalToken,
        "x-open-compute-startup-generation":
          currentStartupGeneration(internalToken),
      },
      body: JSON.stringify({
        key: envelope.loaderKey,
        expectedWorkerCodeSha256: envelope.expected,
        scope,
      }),
    },
  );
  if (!response.ok) {
    const code =
      response.headers.get("x-open-compute-error-code") || "RUNTIME_INTERNAL";
    throw bindingError(code);
  }
  const snapshot: unknown = await response.json();
  assertSnapshot(snapshot);
  if (
    snapshot.loaderKey !== envelope.loaderKey ||
    snapshot.workerCodeSha256 !== envelope.expected ||
    (scope === "runtime" &&
      envelope.routeGeneration !== undefined &&
      snapshot.routeGeneration !== envelope.routeGeneration)
  ) {
    throw bindingError("VERSION_INVARIANT_VIOLATION");
  }
  if (cacheKey) rememberWarmSnapshot(cacheKey, snapshot);
  return snapshot;
}

function snapshotBytes(snapshot: RuntimeSnapshot): number {
  let bytes = 256;
  for (const module of snapshot.modules ?? []) {
    bytes += module.name.length + module.bytesBase64.length;
  }
  for (const binding of snapshot.moduleBindings ?? []) {
    bytes += binding.name.length + binding.bytesBase64.length;
  }
  return bytes;
}

function dropWarmSnapshot(key: string): void {
  const size = warmRuntimeSnapshotSizes.get(key);
  if (size === undefined) return;
  warmRuntimeSnapshotTotal -= size;
  warmRuntimeSnapshots.delete(key);
  warmRuntimeSnapshotSizes.delete(key);
}

function rememberWarmSnapshot(key: string, snapshot: RuntimeSnapshot): void {
  dropWarmSnapshot(key);
  const size = snapshotBytes(snapshot);
  warmRuntimeSnapshots.set(key, snapshot);
  warmRuntimeSnapshotSizes.set(key, size);
  warmRuntimeSnapshotTotal += size;
  while (
    warmRuntimeSnapshots.size > 1 &&
    (warmRuntimeSnapshots.size > WARM_RUNTIME_SNAPSHOTS ||
      warmRuntimeSnapshotTotal > WARM_RUNTIME_SNAPSHOT_BYTES)
  ) {
    const oldest = warmRuntimeSnapshots.keys().next().value;
    if (oldest === undefined || oldest === key) break;
    dropWarmSnapshot(oldest);
  }
}

/** Deduplicate one immutable WorkerLoader assembly while it is in flight. */
export function assembleOnce(
  key: string,
  build: () => Promise<WorkerLoaderWorkerCode>,
): Promise<WorkerLoaderWorkerCode> {
  const current = assembling.get(key);
  if (current) return current;
  const pending = build().finally(() => {
    if (assembling.get(key) === pending) assembling.delete(key);
  });
  assembling.set(key, pending);
  return pending;
}

/** Create a sanitized platform binding error with one stable code. */
export function bindingError(code: string): Error & { stableCode: string } {
  const error = Object.assign(new Error(code), { stableCode: code });
  error.stack = `Error: ${code}`;
  return error;
}

/** Read a platform error code without exposing arbitrary exception fields. */
export function stableCode(error: unknown): string | undefined {
  return error !== null &&
    typeof error === "object" &&
    !Array.isArray(error) &&
    typeof Reflect.get(error, "stableCode") === "string"
    ? (Reflect.get(error, "stableCode") as string)
    : undefined;
}

/** Narrow an untrusted protocol value to a plain record. */
export function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}
